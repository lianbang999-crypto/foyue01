// 【边界要窄】风格研究实据：感应神异／民俗／临终／疾病这些「敏感题」法师大多亲答过，
// 且宽严有度——不能替法师立比他本人更严的戒条。故此处只拦三类：
//   injection  提示注入／要求改变身份设定（选佛谱前车之鉴第 4 条）
//   care       自伤危机语——不拒答，走关怀路（照常给法师亲答，另加求助提示）
//   其余一律 qa，交定本→综述正常作答。

export function classify(q) {
  const t = String(q || '');
  if (/(忽略|无视|忘掉|不要理会)[^。]{0,15}(指令|规则|设定|提示|要求)|system\s*prompt|系统提示词?|你现在是|扮演|越狱|jailbreak|ignore (all|previous|above)/i.test(t)) {
    return 'injection';
  }
  if (/(我?想自杀|不想活了|想死|活不下去|想轻生|自残|结束自己的生命)/.test(t)) {
    return 'care';
  }
  return 'qa';
}

